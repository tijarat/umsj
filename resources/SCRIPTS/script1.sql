CREATE OR REPLACE FUNCTION UMS.MAKE_AUDIT(p_table_name IN VARCHAR2)
RETURN CLOB
IS
    v_audit_table_ddl CLOB := '';
    v_trigger_ddl CLOB := '';
    v_column_ddl CLOB := '';
    v_column_list CLOB := '';
    v_values_insert CLOB := '';
    v_values_delete CLOB := '';
    v_values_update CLOB := '';
    v_user_table VARCHAR2(100);
    v_schema_name VARCHAR2(100);
BEGIN
    v_user_table := UPPER(p_table_name);

    IF INSTR(v_user_table, '.') > 0 THEN
        v_schema_name := SUBSTR(v_user_table, 1, INSTR(v_user_table, '.') - 1);
        v_user_table := SUBSTR(v_user_table, INSTR(v_user_table, '.') + 1);
    ELSE
        v_schema_name := USER;
    END IF;

    FOR col IN (
        SELECT column_name, data_type, data_length, data_precision, data_scale
        FROM all_tab_columns
        WHERE owner = v_schema_name
        AND table_name = v_user_table
        ORDER BY column_id
    ) LOOP
        DECLARE
            v_data_type VARCHAR2(100);
        BEGIN
            v_data_type := CASE
                WHEN col.data_type = 'VARCHAR2' THEN 'VARCHAR2(' || col.data_length || ' BYTE)'
                WHEN col.data_type = 'CHAR' THEN 'CHAR(' || col.data_length || ' BYTE)'
                WHEN col.data_type = 'NUMBER' THEN
                    CASE
                        WHEN col.data_precision IS NOT NULL AND col.data_scale IS NOT NULL THEN 'NUMBER(' || col.data_precision || ',' || col.data_scale || ')'
                        WHEN col.data_precision IS NOT NULL THEN 'NUMBER(' || col.data_precision || ')'
                        ELSE 'NUMBER'
                    END
                WHEN col.data_type IN ('DATE', 'CLOB', 'NCLOB', 'BLOB', 'TIMESTAMP') THEN col.data_type
                ELSE col.data_type
            END;

            v_column_ddl := v_column_ddl || '  O' || col.column_name || ' ' || v_data_type || ',' || CHR(10);
            v_column_ddl := v_column_ddl || '  N' || col.column_name || ' ' || v_data_type || ',' || CHR(10);

            v_column_list := v_column_list || 'O' || col.column_name || ',N' || col.column_name || ',';

            v_values_insert := v_values_insert || 'NULL,:NEW.' || col.column_name || ',';
            v_values_delete := v_values_delete || ':OLD.' || col.column_name || ',NULL,';
            v_values_update := v_values_update || ':OLD.' || col.column_name || ',:NEW.' || col.column_name || ',';
        END;
    END LOOP;

    v_column_list := RTRIM(v_column_list, ',');
    v_values_insert := RTRIM(v_values_insert, ',');
    v_values_delete := RTRIM(v_values_delete, ',');
    v_values_update := RTRIM(v_values_update, ',');

    v_audit_table_ddl := 'CREATE TABLE AUDITOR.' || v_user_table || ' (' || CHR(10) ||
                         v_column_ddl ||
                         '  USERNAME VARCHAR2(30 BYTE),' || CHR(10) ||
                         '  WEB_USER VARCHAR2(100 BYTE),' || CHR(10) ||
                         '  MACHINE VARCHAR2(100 BYTE),' || CHR(10) ||
                         '  IP VARCHAR2(50 BYTE),' || CHR(10) ||
                         '  ACTIVITY_TYPE VARCHAR2(5 BYTE),' || CHR(10) ||
                         '  ACTIVITY_DTE DATE' || CHR(10) ||
                         ');' || CHR(10) || CHR(10);

    v_trigger_ddl := 'CREATE OR REPLACE TRIGGER ' || v_schema_name || '.TRG_' || v_user_table || CHR(10) ||
                     'AFTER INSERT OR DELETE OR UPDATE ON ' || v_schema_name || '.' || v_user_table || CHR(10) ||
                     'FOR EACH ROW' || CHR(10) ||
                     'DECLARE' || CHR(10) ||
                     'BEGIN' || CHR(10) ||
                     ' IF INSERTING THEN' || CHR(10) ||
                     '  INSERT INTO AUDITOR.' || v_user_table || '(' || v_column_list || ',USERNAME,WEB_USER,MACHINE,IP,ACTIVITY_TYPE,ACTIVITY_DTE)' || CHR(10) ||
                     '  VALUES (' || v_values_insert || ',USER,SYS_CONTEXT(''CTX_UMS_WEBUSER'',''WEBUSER''),SYS_CONTEXT(''USERENV'',''HOST''),SYS_CONTEXT(''CTX_UMS_WEBUSER'',''IP''),''I'',SYSDATE);' || CHR(10) ||
                     ' ELSIF DELETING THEN' || CHR(10) ||
                     '  INSERT INTO AUDITOR.' || v_user_table || '(' || v_column_list || ',USERNAME,WEB_USER,MACHINE,IP,ACTIVITY_TYPE,ACTIVITY_DTE)' || CHR(10) ||
                     '  VALUES (' || v_values_delete || ',USER,SYS_CONTEXT(''CTX_UMS_WEBUSER'',''WEBUSER''),SYS_CONTEXT(''USERENV'',''HOST''),SYS_CONTEXT(''CTX_UMS_WEBUSER'',''IP''),''D'',SYSDATE);' || CHR(10) ||
                     ' ELSIF UPDATING THEN' || CHR(10) ||
                     '  INSERT INTO AUDITOR.' || v_user_table || '(' || v_column_list || ',USERNAME,WEB_USER,MACHINE,IP,ACTIVITY_TYPE,ACTIVITY_DTE)' || CHR(10) ||
                     '  VALUES (' || v_values_update || ',USER,SYS_CONTEXT(''CTX_UMS_WEBUSER'',''WEBUSER''),SYS_CONTEXT(''USERENV'',''HOST''),SYS_CONTEXT(''CTX_UMS_WEBUSER'',''IP''),''U'',SYSDATE);' || CHR(10) ||
                     ' END IF;' || CHR(10) ||
                     'END;' || CHR(10) ||
                     '/' || CHR(10);

    RETURN v_audit_table_ddl || CHR(10) || v_trigger_ddl;
END;

